// CC-135: a link for a changed course says so and offers the ideal ghost beside the message. One browser at a time.
import { chromium } from 'playwright';
import { execFileSync, spawn } from 'node:child_process';
import { mkdirSync } from 'node:fs';
const out = process.argv[2] ?? 'test-results/share-offer'; mkdirSync(out, { recursive: true });
const port = Number(process.env.PORT ?? 5883);
const course = process.env.COURSE ?? 'public/assets/demo/lache.course.json';
const vite = spawn('node', ['node_modules/vite/bin/vite.js', '--port', String(port), '--strictPort'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 6000));
const link = execFileSync('node_modules/.bin/tsx', ['scripts/share-link.ts', course, `http://localhost:${port}`]).toString().trim();
const changed = link.replace(/(challenge=1\.)[a-z0-9]+/, '$1zzzzzz');
const results = []; const ok = (n, p, note = '') => { results.push(p); console.log(p ? 'PASS' : 'FAIL', n, note); };
const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--no-sandbox'] });
const page = await (await b.newContext({ viewport: { width: 1280, height: 720 } })).newPage(); const errs = []; page.on('pageerror', (e) => errs.push(String(e)));
await page.goto(`${changed}&welcome=0&tour=0`, { waitUntil: 'load' });
const banner = await page.waitForSelector('#challenge-banner', { timeout: 60000 }).then((e) => e.innerText()).catch(() => '');
ok('the message says the course changed', /has changed/.test(banner), banner.replace(/\n/g, ' | '));
ok('the offer sits beside the message', /Chase the ideal run instead/.test(banner));
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/offer.png` });
const before = await page.textContent('#ghost-chip');
await page.evaluate(() => [...document.querySelectorAll('#challenge-banner button')].find((x) => /Chase the ideal/.test(x.textContent)).click());
await page.waitForFunction(() => /Ideal run/.test(document.querySelector('#ghost-chip').textContent), null, { timeout: 60000 }).catch(() => {});
const after = await page.textContent('#ghost-chip');
ok('the click turns the ideal ghost on', /Ideal run/.test(after) && !/Ideal run/.test(before), `${before} -> ${after}`);
ok('the banner goes away', !(await page.$('#challenge-banner')));
await page.screenshot({ path: `${out}/after.png` });
const dmg = await b.newPage();
await dmg.goto(`${link.replace(/challenge=[^&]*/, 'challenge=1.abc.')}&welcome=0&tour=0`, { waitUntil: 'load' });
const tb = await dmg.waitForSelector('#challenge-banner', { timeout: 60000 }).then((e) => e.innerText()).catch(() => '');
ok('a damaged link offers nothing', /damaged/.test(tb) && !/Chase/.test(tb), tb.replace(/\n/g, ' | '));
ok('no page errors', errs.length === 0, errs.join(' | ').slice(0, 300));
await b.close(); vite.kill(); process.exit(results.every(Boolean) ? 0 : 1);
