// CC-134: a tag on the report goes into the link, the banner and the ghost chip; a blocked tag makes no link. One browser at a time.
import { chromium } from 'playwright';
import { execFileSync, spawn } from 'node:child_process';
import { mkdirSync } from 'node:fs';
const out = process.argv[2] ?? 'test-results/share-nick'; mkdirSync(out, { recursive: true });
const port = Number(process.env.PORT ?? 5883);
const course = process.env.COURSE ?? 'public/assets/demo/lache.course.json';
const vite = spawn('node', ['node_modules/vite/bin/vite.js', '--port', String(port), '--strictPort'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 6000));
const link = execFileSync('node_modules/.bin/tsx', ['scripts/share-link.ts', course, `http://localhost:${port}`]).toString().trim();
const results = []; const ok = (n, p, note = '') => { results.push(p); console.log(p ? 'PASS' : 'FAIL', n, note); };
const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--no-sandbox'] });
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 }, permissions: ['clipboard-read', 'clipboard-write'] });
const page = await ctx.newPage(); const errs = []; page.on('pageerror', (e) => errs.push(String(e)));
await page.goto(`${link}&autoplay=1&welcome=0&tour=0`, { waitUntil: 'load' });
const got = await page.waitForSelector('#report-again', { timeout: 300000 }).then(() => true).catch(() => false);
ok('the friend\'s run ends in the report', got);
const copy = async (tag) => {
  // a friend's challenge page has no board, so no name box: the link reads the name the player saved from the top box (localStorage cc.nick)
  const shown = await page.evaluate((t) => { localStorage.setItem('cc.nick', t); return localStorage.getItem('cc.nick'); }, tag);
  await page.evaluate(() => navigator.clipboard.writeText(''));
  await page.click('#share-copy');
  await page.waitForTimeout(800);
  return { shown, text: await page.textContent('#share-copy'), url: await page.evaluate(() => navigator.clipboard.readText()) };
};
const a = await copy('amy!');
ok('the box keeps case and symbols', a.shown === 'amy!', a.shown);
ok('the link carries the tag', /challenge=1\.[a-z0-9]+\.amy%2521\./.test(a.url), a.url.slice(0, 110));
await page.screenshot({ path: `${out}/report-tag.png` });
const bad = await copy('ass');
ok('a blocked tag makes no link and says so', bad.url === '' && /another name/i.test(bad.text), bad.text);
const none = await copy('');
ok('an empty tag still makes the plain link', /challenge=1\.[a-z0-9]+\.\.[dr]/.test(none.url));
const again = await ctx.newPage();
await again.goto(`${a.url}&welcome=0&tour=0`, { waitUntil: 'load' });
const banner = await again.waitForSelector('#challenge-banner', { timeout: 60000 }).then((e) => e.innerText()).catch(() => '');
ok('the banner names the tag', /Beat amy!: \d+\.\d\d s/.test(banner), banner.replace(/\n/g, ' | '));
const chip = await again.textContent('#ghost-chip').catch(() => '');
ok('the ghost chip names the tag', /amy!'s run/.test(chip), chip);
await again.screenshot({ path: `${out}/banner-tag.png` });
ok('no page errors', errs.length === 0, errs.join(' | ').slice(0, 300));
await b.close(); vite.kill(); process.exit(results.every(Boolean) ? 0 : 1);
