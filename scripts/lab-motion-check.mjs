// Lab 13 (Video to motion) in the browser: off without the labs switch; with it, opens already run on a failing clip, a passing clip plays, a broken one is held back.
import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { mkdirSync } from 'node:fs';
const port = process.env.PORT ?? '5173';
const server = spawn('node', ['node_modules/vite/bin/vite.js', '--port', port, '--strictPort'], { stdio: 'ignore' });
const result = {};
let failed = false;
const check = (name, ok, extra = '') => { result[name] = ok ? 'ok' : `FAILED ${extra}`; if (!ok) failed = true; };
try {
  await new Promise((r) => setTimeout(r, 3000));
  const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
  mkdirSync('test-results/lab-motion', { recursive: true });
  const base = `http://localhost:${port}`;
  const errors = [];
  const off = await (await browser.newContext({ viewport: { width: 1280, height: 720 } })).newPage();
  await off.goto(`${base}/?mode=lab-motion&labs=0&backend=webgl2`);
  await off.waitForSelector('#lab-motion', { timeout: 60000 });
  check('off message', (await off.textContent('#lab-motion')).includes('Labs are switched off'));
  const page = await (await browser.newContext({ viewport: { width: 1280, height: 1000 } })).newPage();
  page.on('pageerror', (e) => errors.push(e.message.slice(0, 200)));
  await page.goto(`${base}/?mode=lab-motion&labs=1&backend=webgl2`);
  await page.waitForFunction(() => document.documentElement.dataset.labPopulated === 'lab-motion', null, { timeout: 60000 });
  check('opens on the failing roll', (await page.textContent('#mo-s4')).includes('fails'));
  check('gate table has rows', (await page.locator('#mo-all tbody tr').count()) === 10);
  check('recorded run filled', (await page.textContent('#mo-rec')).includes('After repairs'));
  await page.waitForFunction(() => document.documentElement.dataset.motionRookie === '1', null, { timeout: 90000 }).catch(() => {});
  check('held back shown', (await page.locator('#mo-held').isVisible()) && (await page.textContent('#mo-held')).includes('Held back'));
  await page.selectOption('#mo-clip', 'run');
  await page.waitForTimeout(1500);
  check('run passes and plays', (await page.textContent('#mo-s4')).includes('passes') && !(await page.locator('#mo-held').isVisible()));
  await page.selectOption('#mo-clip', 'sink');
  check('sunk feet held back', (await page.textContent('#mo-held')).includes('Feet stay above the floor'));
  await page.click('#mo-open-w8');
  await page.waitForSelector('#mo-w8-body #sg-gate tr', { timeout: 30000 });
  check('Lab 8 panel woven into the gate step (slider and gate table)', (await page.locator('#mo-w8-body #sg-s').count()) === 1 && (await page.locator('#mo-w8-body #sg-gate tr').count()) > 5);
  await page.fill('#mo-w8-body #sg-s', '4'); await page.dispatchEvent('#mo-w8-body #sg-s', 'input');
  check('smoothing slider reruns the panel', (await page.textContent('#mo-w8-body #sg-s-v')).length > 0);
  // the reach panel is open beside the step 5 view from the start
  await page.waitForSelector('#mo-w3-body #ik-solver button', { timeout: 30000 });
  check('Lab 3 panel woven into the retarget step (solver buttons)', (await page.locator('#mo-w3-body #ik-solver button').count()) >= 2);
  await page.screenshot({ path: 'test-results/lab-motion/lab-motion-woven.png', fullPage: true });
  await page.selectOption('#mo-clip', 'roll-whole');
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'test-results/lab-motion/lab-motion.png', fullPage: true });
  check('no page errors', errors.length === 0, errors.join(' | '));
  await browser.close();
} finally { server.kill(); }
console.log(JSON.stringify(result, null, 2));
process.exit(failed ? 1 : 0);
