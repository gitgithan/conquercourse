// CC-136: a course made in the editor travels in the link and opens as the same run in a fresh page. One browser at a time.
import { chromium } from 'playwright';
import { execFileSync, spawn } from 'node:child_process';
import { mkdirSync } from 'node:fs';
const out = process.argv[2] ?? 'test-results/share-made'; mkdirSync(out, { recursive: true });
const port = Number(process.env.PORT ?? 5883);
const course = process.env.COURSE ?? 'public/assets/demo/lache.course.json';
const vite = spawn('node', ['node_modules/vite/bin/vite.js', '--port', String(port), '--strictPort'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 6000));
const link = execFileSync('node_modules/.bin/tsx', ['scripts/share-link.ts', course, `http://localhost:${port}`], { env: { ...process.env, MADE: '1' } }).toString().trim();
const results = []; const ok = (n, p, note = '') => { results.push(p); console.log(p ? 'PASS' : 'FAIL', n, note); };
ok('the link carries the course and the keys, and is short enough', /[?&]made=/.test(link) && /challenge=/.test(link) && link.length < 2100, `${link.length} chars`);
const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--no-sandbox'] });
const page = await (await b.newContext({ viewport: { width: 1280, height: 720 } })).newPage(); const errs = []; page.on('pageerror', (e) => errs.push(String(e)));
await page.goto(`${link}&welcome=0&tour=0`, { waitUntil: 'load' });
const banner = await page.waitForSelector('#challenge-banner', { timeout: 60000 }).then((e) => e.innerText()).catch(() => '');
ok('the made course opens and the friend run is on it', /Beat this time: \d+\.\d\d s/.test(banner), banner.replace(/\n/g, ' | '));
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/opened.png` });
const bad = await b.newPage();
await bad.goto(`${link.replace(/made=[^&]*/, 'made=dAAAA')}&welcome=0&tour=0`, { waitUntil: 'load' });
const tb = await bad.waitForSelector('#challenge-banner', { timeout: 60000 }).then((e) => e.innerText()).catch(() => '');
ok('a damaged course is refused in plain words, with no offer', /too big or is damaged/.test(tb) && !/Chase/.test(tb), tb.replace(/\n/g, ' | '));
await bad.screenshot({ path: `${out}/refused.png` });
const off = await b.newPage();
await off.goto(`${link}&share=0&welcome=0&tour=0`, { waitUntil: 'load' });
await off.waitForTimeout(3000);
ok('?share=0 turns it off: no banner', !(await off.$('#challenge-banner')));
ok('no page errors', errs.length === 0, errs.join(' | ').slice(0, 300));
await b.close(); vite.kill(); process.exit(results.every(Boolean) ? 0 : 1);
