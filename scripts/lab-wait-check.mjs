// Hide the wait in the browser at 1280 px: off without the labs switch; with it every output is filled on open, the steps scrub, break-it changes the comparison.
// Screenshots go to test-results/lab-wait/.
import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { mkdirSync } from 'node:fs';
const port = process.env.PORT ?? '5183';
const server = spawn('node', ['node_modules/vite/bin/vite.js', '--port', port, '--strictPort'], { stdio: 'ignore' });
const result = {};
let failed = false;
const check = (name, ok, extra = '') => { result[name] = ok ? 'ok' : `FAILED ${extra}`; if (!ok) failed = true; };
try {
  for (let i = 0; i < 90; i++) { try { await fetch(`http://localhost:${port}/`); break; } catch { await new Promise((r) => setTimeout(r, 1000)); } }
  const browser = await chromium.launch({ args: ['--no-sandbox', ...(process.env.WEBGL2 ? ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] : [])] });
  mkdirSync('test-results/lab-wait', { recursive: true });
  const base = `http://localhost:${port}`;
  const errors = [];
  const off = await (await browser.newContext({ viewport: { width: 1280, height: 720 } })).newPage();
  off.on('pageerror', (e) => errors.push(e.message.slice(0, 200)));
  await off.goto(`${base}/?mode=lab-wait&labs=0&backend=webgl2`);
  await off.waitForSelector('#lab-wait', { timeout: 60000 });
  check('off message', (await off.textContent('#lab-wait')).includes('Labs are switched off'));
  const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
  page.on('pageerror', (e) => errors.push(e.message.slice(0, 200)));
  await page.goto(`${base}/?mode=lab-wait&labs=1&backend=webgl2`);
  await page.waitForFunction(() => document.documentElement.dataset.labPopulated === 'lab-wait', null, { timeout: 90000 });
  check('intro promises immediate feedback', (await page.textContent('#lab-default-note')).includes('effect immediately'));
  check('reuse preview populated', await page.getAttribute('#lw-reuse', 'data-ready') === 'true');
  check('our setting removes repeated work', await page.getAttribute('#lw-reuse', 'data-work') === '9');
  await page.screenshot({ path: 'test-results/lab-wait/reuse-start.png' });
  await page.focus('#lr-assets'); await page.keyboard.press('Space');
  check('keyboard choices redraw immediately', await page.getAttribute('#lw-reuse', 'data-work') === '22');
  await page.keyboard.press('Space');
  await page.click('#lr-rebuild');
  check('rebuild choice redraws immediately', await page.getAttribute('#lw-reuse', 'data-work') === '31');
  check('resources have inspectable identities', (await page.textContent('#lr-diagram')).includes('#1'));
  await page.click('#lr-ours');
  await page.uncheck('#lr-cleanup');
  check('cleanup preview shows future leftovers', (await page.textContent('#lr-metrics')).includes('6 left over'));
  for (let i = 0; i < 3; i++) await page.click('#lr-switch');
  check('repeated switches accumulate leftovers', await page.getAttribute('#lw-reuse', 'data-leaked') === '18');
  await page.check('#lr-cleanup'); await page.click('#lr-switch');
  check('cleanup prevents new leaks, keeps earlier ones visible', await page.getAttribute('#lw-reuse', 'data-leaked') === '18');
  await page.click('#lr-reset');
  check('reset clears history', await page.getAttribute('#lw-reuse', 'data-switches') === '0' && await page.getAttribute('#lw-reuse', 'data-leaked') === '0');
  for (let i = 0; i < 3; i++) await page.click('#lr-switch');
  check('clean repeated switches stay flat', await page.getAttribute('#lw-reuse', 'data-leaked') === '0');
  await page.$eval('#lr-scrub', (e) => { e.value = '35'; e.dispatchEvent(new Event('input', { bubbles: true })); });
  check('scrubber explains the blocking stage', (await page.textContent('#lr-stage')).startsWith('Close old course:'));
  await page.click('[data-resource="worker"]');
  check('resource inspection explains cancellation', (await page.textContent('#lr-detail')).includes('cancelled'));
  await page.click('#lr-play'); await page.waitForTimeout(100);
  check('replay animates', Number(await page.$eval('#lr-scrub', (e) => e.value)) > 0 && Number(await page.$eval('#lr-scrub', (e) => e.value)) < 100);
  await page.click('#lr-play');
  await page.$eval('#lr-scrub', (e) => { e.value = '100'; e.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.$eval('#lab-wait', (e) => { e.scrollTop = 0; });
  await page.screenshot({ path: 'test-results/lab-wait/reuse.png' });
  await page.uncheck('#lr-cleanup'); await page.click('#lr-switch'); await page.click('#lr-play');
  await page.screenshot({ path: 'test-results/lab-wait/reuse-leftovers.png' });
  check('no horizontal overflow', await page.$eval('#lab-wait', (e) => e.scrollWidth <= e.clientWidth));
  await page.click('#lw-show-search');
  check('experiment instructions follow the selected tab', (await page.textContent('#lab-wait .wrap > div p.small')).includes('two lanes'));
  const tiles = await page.textContent('#lw-tiles');
  check('meters filled', !/undefined|NaN/.test(tiles) && tiles.includes('First word on screen'), tiles.slice(0, 300));
  check('nav names the Lab', (await page.textContent('#labs-nav')).includes('Hide the wait'));
  const pills = await page.$$eval('#lw-ch .pill', (e) => e.map((x) => x.textContent));
  check('four challenges', pills.length === 4, String(pills));
  const worst = async () => (await page.$$eval('#lw-tiles .tile', (e) => e.map((x) => x.textContent))).join('|');
  const before = await worst();
  await page.click('#lw-presets button[data-id="bare"]');
  const after = await worst();
  check('bare preset changes the meters', before !== after && /Frames missed/.test(after), after);
  const bareFail = await page.$$eval('#lw-ch .pill.fail', (e) => e.length);
  check('bare fails challenges', bareFail >= 2, String(bareFail));
  await page.screenshot({ path: 'test-results/lab-wait/bare.png', fullPage: true });
  await page.click('#lw-presets button[data-id="ours"]');
  const failOurs = await page.$$eval('#lw-ch .pill.fail', (e) => e.length);
  check('our setting passes most', failOurs <= 1, String(failOurs));
  await page.$eval('#lw-cold', (e) => { e.value = '100'; e.dispatchEvent(new Event('input', { bubbles: true })); });
  check('cold knob moves the meter', (await page.textContent('#lw-cold-v')) === '100 s');
  await page.click('#lw-eq-btn');
  check('maths opens', (await page.textContent('#lw-eq')).includes('wall time'));
  check('links the Search Lab', (await page.textContent('#lw-l-search')).includes('Search'));
  await page.$eval('#lab-wait', (e) => { e.scrollTop = 0; });
  await page.screenshot({ path: 'test-results/lab-wait/ours.png' });
  await page.goto(`${base}/?mode=lab-wait&labs=1&waitreuse=0`);
  await page.waitForFunction(() => document.documentElement.dataset.labWaitReady === '1');
  check('feature opt-out retains the old experiment', await page.locator('#lw-original').isVisible() && await page.locator('#lw-show-reuse').isHidden());
  const reduced = await (await browser.newContext({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' })).newPage();
  reduced.on('pageerror', (e) => errors.push(e.message));
  await reduced.goto(`${base}/?mode=lab-wait&labs=1`);
  await reduced.locator('#lw-reuse[data-ready=true]').waitFor();
  await reduced.click('#lr-switch');
  check('reduced motion completes without animation', await reduced.inputValue('#lr-scrub') === '100' && await reduced.textContent('#lr-play') === 'Replay switch');
  await reduced.close();
  check('no page errors', errors.length === 0, errors.join(' | '));
  await browser.close();
} catch (e) { check('run', false, String(e)); } finally { server.kill(); }
console.log(JSON.stringify(result, null, 2));
process.exit(failed ? 1 : 0);
