"""Build the starter clip set: run, leap, land, hang, swing, wall run-up, grab.

CMU trials are imported with ccpipe.cmu from raw files kept outside git (../conquercourse-assets/cmu/);
Kimodo candidates (pipelines/kimodo_clips.py) are read from a folder of its JSON outputs.
Every clip is repaired, then gated; only clips that pass are written to public/assets/motion/,
the rest go to public/assets/experiments/ with their gate report. Run from the repo root:

    python pipelines/build_starter.py --cmu ../conquercourse-assets/cmu --kimodo <dir> --out-eval data/eval/starter-clips
"""
import argparse
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
from ccpipe import cmu, gate, motion, repairs, sheet  # noqa: E402
from ccpipe.clip import Clip  # noqa: E402

CMU_BASE = "http://mocap.cs.cmu.edu/subjects"

# name -> (trial, first frame, last frame (30 fps, exclusive; None = to the end), supportedBy, what it is)
CMU_CLIPS = {
    "run": ("09_01", 0, None, None, "a steady run"),
    "leap": ("49_04", 0, None, None, "run-up, a leap through the air, landing"),
    "land": ("49_05", 17, None, None, "the last of the flight, touch-down and recovery"),
    "hang": ("01_10", 385, 440, ["playground bars"], "hanging by the hands, feet off the ground"),
    "swing": ("01_10", 360, 460, ["playground bars"], "hanging and swinging the legs"),
    "reach": ("14_09", 625, 680, ["something overhead"], "a hop up to reach and grab something overhead"),
}
# clip name -> the starter move it serves (the others are extras)
# Kimodo prompt key -> (clip name, supportedBy, what the motion must show; fixed before the runs, see the README)
KIMODO_CLIPS = {
    "leap_a": ("kimodo_leap", None, "flight"), "leap_b": ("kimodo_leap", None, "flight"),
    "wall_a": ("wall_runup_grab", ["a wall"], "wall_grab"), "wall_b": ("wall_runup_grab", ["a wall"], "wall_grab"),
    "wall_c": ("wall_runup_grab", ["a wall"], "wall_grab"),
    "wall_a3": ("wall_runup_grab", ["a wall"], "wall_grab"), "wall_b3": ("wall_runup_grab", ["a wall"], "wall_grab"),
    "wall_c3": ("wall_runup_grab", ["a wall"], "wall_grab"),
    "grab_a": ("kimodo_grab", ["a bar"], "grip"), "grab_b": ("kimodo_grab", ["a bar"], "grip"),
}
# clip name -> the starter move it serves (the others are extras)
MOVES = {"wall_runup_grab": "wall_runup_grab"}
EXPECTS = {
    "flight": "a flight of at least 0.2 s while the hips travel at least 2 m",
    "wall_grab": "a foot planted 0.4-1.6 m up while running (travel at least 2 m), then a hand grip above the head with feet off the floor for at least 0.3 s",
    "grip": "a hand grip above the head with feet off the floor for at least 0.5 s",
}


def expectation(clip, kind):
    """(ok, numbers): does the motion actually show the move the prompt asked for?"""
    f, fps = clip.frames, clip.fps
    travel = float(np.linalg.norm(f[-1, 0, [0, 2]] - f[0, 0, [0, 2]]))
    grip = int(motion.grip_frames(f, fps).sum())
    if kind == "flight":
        fl = motion.longest_flight(motion.supported(f, fps, 0.0))
        return (fl is not None and travel >= 2.0), {"flight_frames": 0 if fl is None else fl[1] - fl[0], "travel_m": round(travel, 2)}
    if kind == "wall_grab":
        plant = motion.planted_foot_height(f, fps)
        return (0.4 <= plant <= 1.6 and travel >= 2.0 and grip >= 0.3 * fps), {"plant_m": round(plant, 2), "travel_m": round(travel, 2), "grip_frames": grip}
    return grip >= 0.5 * fps, {"grip_frames": grip}


def finish(clip, name, source, what, supported_by):
    meta = {"id": name, "move": MOVES.get(name, name), "what": what, "source": source, "credit": cmu.CREDIT if source.startswith("CMU") else
            "Generated by Kimodo-SOMA-RP (NVIDIA Open Model License; NVIDIA claims no rights in outputs)."}
    if supported_by:
        meta["supportedBy"] = supported_by
    clip = clip.copy(**meta)
    raw_report = gate.run_gate(clip)
    raw_g = raw_report["hard"]["flight_is_ballistic"]["value"]
    fixed, log = repairs.repair(clip)
    report = gate.run_gate(fixed)
    sup = motion.supported(fixed.frames, fixed.fps)
    fl = motion.longest_flight(sup)
    extra = {"gate": report, "raw_gate_pass": raw_report["pass"], "raw_fitted_gravity": raw_g, "repairs": log}
    if fl and not supported_by:
        extra.update(takeoff=int(fl[0]), landing=int(fl[1]))
    return fixed.copy(**extra)


def build_cmu(raw_dir):
    out = {}
    for name, (trial, a, b, sup, what) in CMU_CLIPS.items():
        subj = trial.split("_")[0]
        with open(os.path.join(raw_dir, f"{subj}.asf")) as f:
            asf = f.read()
        with open(os.path.join(raw_dir, f"{trial}.amc")) as f:
            amc = f.read()
        full = cmu.import_trial(asf, amc)
        frames = cmu.orient(full.frames[a:b])  # re-centre on the window
        out[name] = finish(Clip(frames, 30.0), name, f"CMU {trial} ({CMU_BASE}/{subj}/{trial}.amc)", what, sup)
    return out


def build_kimodo(kdirs):
    """{clip name: [candidate clips from every variant and sample]}; each carries `expects` and `meets`."""
    out = {}
    for key, (name, sup, kind) in KIMODO_CLIPS.items():
        paths = [os.path.join(k, f"{key}.json") for k in kdirs]
        paths = [p for p in paths if os.path.exists(p)]
        if not paths:
            continue
        path = paths[0]
        with open(path) as f:
            d = json.load(f)
        for i, smp in enumerate(np.array(d["samples"])):
            clip = Clip(cmu.orient(smp), d["fps"])
            c = finish(clip, name, f"Kimodo-SOMA-RP, prompt {key}, sample {i}", d["prompt"], sup)
            meets, nums = expectation(c, kind)
            out.setdefault(name, []).append(c.copy(candidate=f"{key}_s{i}", expects=EXPECTS[kind], meets=bool(meets), expect_numbers=nums))
    return out


def error_score(c):
    r = c.meta["gate"]["hard"]["flight_is_ballistic"]
    return 0.0 if r["value"] is None else abs(r["value"] - 9.81)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cmu", required=True)
    ap.add_argument("--kimodo", action="append", default=[], help="a folder of kimodo_clips.py outputs (repeatable)")
    ap.add_argument("--out-eval", default="data/eval/starter-clips")
    ap.add_argument("--motion", default="public/assets/motion")
    ap.add_argument("--experiments", default="public/assets/experiments/starter-clips")
    ap.add_argument("--candidates", default=None, help="folder for every Kimodo candidate (outside git, e.g. ../conquercourse-assets/starter-clips/candidates)")
    a = ap.parse_args()
    for d in (a.out_eval, a.motion, a.experiments, a.candidates, os.path.join(a.out_eval, "outputs")):
        if d:
            os.makedirs(d, exist_ok=True)
    index = {}

    def place(clip, fname, label):
        ok = clip.meta["gate"]["pass"]
        folder = a.motion if ok else a.experiments
        clip.save(os.path.join(folder, fname + ".json"))
        sheet.contact_sheet(clip, os.path.join(a.out_eval, "outputs", fname + ".png"), n=12, title=f"{label} ({'pass' if ok else 'FAIL'})")
        index[fname] = {"pass": ok, "folder": folder, "source": clip.meta["source"], "frames": clip.n,
                        "failed": gate.failures(clip.meta["gate"]), "raw_gate_pass": clip.meta["raw_gate_pass"], "raw_fitted_gravity": clip.meta["raw_fitted_gravity"],
                        "repairs": clip.meta["repairs"], "soft_failed": [k for k, r in clip.meta["gate"]["soft"].items() if not r["ok"]]}

    for name, clip in build_cmu(a.cmu).items():
        place(clip, name, name)
    if a.kimodo:
        for name, cands in build_kimodo(a.kimodo).items():
            good = [c for c in cands if c.meta["gate"]["pass"] and c.meta["meets"]]
            best = min(good, key=error_score) if good else None
            for c in cands:
                tag = c.meta["candidate"]
                if c is best:
                    place(c, MOVES.get(name, name), f"{name} ({tag})")
                else:  # not shipped: all candidates are kept outside git, and the first sample of each prompt in the experiment folder
                    if a.candidates:
                        c.save(os.path.join(a.candidates, f"{name}_{tag}.json"))
                    if tag.endswith("_s0"):
                        c.save(os.path.join(a.experiments, f"{name}_{tag}.json"))
                    index[f"{name}_{tag}"] = {"pass": c.meta["gate"]["pass"], "meets_expectation": c.meta["meets"],
                                              "expect_numbers": c.meta["expect_numbers"], "failed": gate.failures(c.meta["gate"]),
                                              "folder": a.experiments, "shipped": False}
            index[f"_{name}_summary"] = {"candidates": len(cands), "gate_pass": sum(c.meta["gate"]["pass"] for c in cands),
                                         "meets_expectation": sum(c.meta["meets"] for c in cands), "both": len(good),
                                         "shipped": None if best is None else best.meta["candidate"]}
    with open(os.path.join(a.out_eval, "outputs", "index.json"), "w") as f:
        json.dump(index, f, indent=1)
    for k, v in index.items():
        print(k, v if k.startswith("_") else ("PASS" if v["pass"] else "FAIL " + ",".join(v["failed"])))


if __name__ == "__main__":
    main()
