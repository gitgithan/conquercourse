"""Motion on demand (CC-64): from a move name to a gated clip for the Rookie.

    python pipelines/motion_on_demand.py roll --cmu-index <cmu-index.json> --cmu <dir of ASF/AMC> [--ship]

Steps (docs/motion-pipeline.md): 1 search the CMU index by the move's terms and import what is there, 2 if no CMU trial shows the
move, ask Kimodo on Modal (text prompts, a cost cap, at most one container), 3 repair, gate and move-check every candidate,
4 write data/eval/motion-<move>/ (inputs, outputs, run.json, contact sheet) and, with --ship, the best passing clip to
public/assets/motion/<move>.json. Nothing is shipped that fails the gate or the move check."""
import argparse
import json
import os
import subprocess
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from ccpipe import cmu, gate, movecheck, repairs, sheet  # noqa: E402
from ccpipe.clip import Clip  # noqa: E402

MODAL_L4_USD_PER_HOUR = 0.80  # an estimate of Modal's list price for one L4, not a measured bill: check the dashboard
CAP_USD = 15.0                # approved by the product owner on 2026-10-28 for this pipeline


def judge(clip, move, source, check):
    """Repair, gate and move-check one candidate -> the repaired clip with its reports in the meta."""
    ok_move, numbers, window = movecheck.CHECKS[check](clip)
    if window is not None and check != "generic":
        clip = movecheck.trim(clip, window)
        ok_move, numbers, window = movecheck.CHECKS[check](clip)
    fixed, log = repairs.repair(clip)
    report = gate.run_gate(fixed)
    return fixed.copy(id=move, move=move, source=source, gate=report, repairs=log, move_check={"ok": bool(ok_move), **numbers}), report["pass"], ok_move


CMU_BASE = "http://mocap.cs.cmu.edu/subjects"
MAX_FETCH = 12  # trials fetched per run: the files are free to use (credit requested) but they are CMU's server, not ours


def fetch_cmu(hits, cmu_dir):
    """Download the missing ASF and AMC files of the hits into cmu_dir (outside git); returns the ids that could not be fetched."""
    import urllib.request
    failed = []
    for h in hits[:MAX_FETCH]:
        subj = h["id"].split("_")[0]
        for name in (f"{subj}.asf", f"{h['id']}.amc"):
            dest = os.path.join(cmu_dir, name)
            if os.path.exists(dest):
                continue
            try:
                urllib.request.urlretrieve(f"{CMU_BASE}/{subj}/{name}", dest)
            except Exception as e:  # a missing file is reported, never faked
                print("could not fetch", name, e)
                failed.append(h["id"])
                break
    return failed


def from_cmu(spec, hits, cmu_dir, move, check):
    """Import the CMU hits that exist on disk, whole trial each, and judge them."""
    out, skipped = [], []
    for h in hits:
        subj = h["id"].split("_")[0]
        asf, amc = (os.path.join(cmu_dir, n) for n in (f"{subj}.asf", f"{h['id']}.amc"))
        if not (os.path.exists(asf) and os.path.exists(amc)):
            skipped.append(h["id"])
            continue
        with open(asf) as fa, open(amc) as fm:
            clip = cmu.import_trial(fa.read(), fm.read(), h["fps"])
        c, gate_ok, move_ok = judge(clip, move, f"CMU {h['id']} ({h['desc']})", check)
        out.append((h["id"], c.copy(credit=cmu.CREDIT), gate_ok, move_ok))
    return out, skipped


def run_kimodo(spec, move, work, samples):
    """Kimodo text prompts on Modal through pipelines/kimodo_clips.py; returns (folder, wall seconds)."""
    pf = os.path.join(work, "prompts.json")
    with open(pf, "w") as f:
        json.dump({k: [v, spec["seconds"]] for k, v in spec["prompts"].items()}, f, indent=2)
    out = os.path.join(work, "kimodo")
    t = time.time()
    subprocess.run(["modal", "run", os.path.join(HERE, "kimodo_clips.py"), "--out", out, "--samples", str(samples), "--prompts-file", pf], check=True)
    return out, time.time() - t


def from_kimodo(folder, spec, move, check):
    out = []
    for key in spec["prompts"]:
        path = os.path.join(folder, f"{key}.json")
        if not os.path.exists(path):
            continue
        with open(path) as f:
            d = json.load(f)
        for i, smp in enumerate(np.array(d["samples"])):
            clip = Clip(cmu.orient(smp), d["fps"])
            c, gate_ok, move_ok = judge(clip, move, f"Kimodo-SOMA-RP, prompt {key}, sample {i}", check)
            c = c.copy(credit="Generated by Kimodo-SOMA-RP (NVIDIA Open Model License; NVIDIA claims no rights in outputs).", prompt=d["prompt"])
            out.append((f"{key}_s{i}", c, gate_ok, move_ok))
    return out


def score(c):
    """Lower is better among candidates that passed both: a turn close to one full circle, fewer soft-rule failures."""
    mc = c.meta["move_check"]
    turn = abs(mc.get("turn_in_window_deg", 360) - 360)
    return turn + 20 * sum(not r["ok"] for r in c.meta["gate"]["soft"].values())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("move")
    ap.add_argument("--moves", default=os.path.join(HERE, "moves.json"))
    ap.add_argument("--cmu-index", default=None, help="cmu-index.json (id, subject, desc, fps per trial)")
    ap.add_argument("--cmu", default=None, help="folder with the CMU <subject>.asf and <trial>.amc files (outside git)")
    ap.add_argument("--kimodo", default=None, help="reuse a folder of kimodo_clips.py outputs instead of running Modal")
    ap.add_argument("--fetch", action="store_true", help="download the missing CMU files of the hits (free to use, credit requested)")
    ap.add_argument("--no-generate", action="store_true", help="CMU only: never start a Modal run")
    ap.add_argument("--samples", type=int, default=6)
    ap.add_argument("--out", default=None)
    ap.add_argument("--ship", action="store_true", help="write the best passing clip to public/assets/motion/<move>.json")
    ap.add_argument("--candidates", default=None, help="folder outside git for every candidate clip")
    a = ap.parse_args()

    with open(a.moves) as f:
        spec = json.load(f).get(a.move)
    if spec is None:
        sys.exit(f"no move '{a.move}' in {a.moves}")
    out = a.out or os.path.join("data", "eval", f"motion-{a.move}")
    os.makedirs(os.path.join(out, "inputs"), exist_ok=True)
    os.makedirs(os.path.join(out, "outputs"), exist_ok=True)
    run = {"move": a.move, "serves": spec["serves"], "started": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "steps": []}

    # 1. CMU
    cands = []
    hits = []
    if a.cmu_index:
        hits = movecheck.search_cmu(movecheck.load_index(a.cmu_index), spec["cmu_terms"], spec.get("cmu_skip", []))
    run["cmu"] = {"terms": spec["cmu_terms"], "skip": spec.get("cmu_skip", []), "hits": hits}
    with open(os.path.join(out, "inputs", "cmu-hits.json"), "w") as f:
        json.dump(hits, f, indent=1)
    if hits and a.cmu:
        if a.fetch:
            os.makedirs(a.cmu, exist_ok=True)
            run["cmu"]["fetch_failed"] = fetch_cmu(hits, a.cmu)
        got, skipped = from_cmu(spec, hits, a.cmu, a.move, spec["check"])
        cands += got
        run["cmu"]["skipped_not_on_disk"] = skipped
    print(f"CMU: {len(hits)} trials mention {spec['cmu_terms']}")
    for h in hits:
        print("   ", h["id"], h["desc"])
    cmu_good = [c for c in cands if c[2] and c[3]]
    run["cmu"]["candidates"] = [{"id": i, "gate_pass": g, "move_check_pass": m, "move_check": c.meta["move_check"]} for i, c, g, m in cands]

    # 2. Kimodo, only if CMU gave nothing that passes both
    if not cmu_good and not a.no_generate:
        spent = 0.0
        if a.kimodo:
            folder = a.kimodo
            kr = os.path.join(folder, "kimodo_run.json")  # the earlier run's own record: wall time of the Modal job and the price assumed
            if os.path.exists(kr):
                with open(kr) as f:
                    secs = json.load(f)["wall_s"]
                run["kimodo"] = {"reused": folder, "wall_s": secs, "estimated_usd": round(secs / 3600 * MODAL_L4_USD_PER_HOUR, 3), "usd_per_hour_assumed": MODAL_L4_USD_PER_HOUR, "cap_usd": CAP_USD}
        else:
            print("No CMU trial passes the gate and the move check: asking Kimodo on Modal")
            folder, secs = run_kimodo(spec, a.move, os.path.join(out, "inputs"), a.samples)
            spent = secs / 3600 * MODAL_L4_USD_PER_HOUR
            run["kimodo"] = {"wall_s": round(secs, 1), "estimated_usd": round(spent, 2), "usd_per_hour_assumed": MODAL_L4_USD_PER_HOUR, "cap_usd": CAP_USD}
            if spent > CAP_USD:
                sys.exit(f"over the cap: about ${spent:.2f}")
        cands += from_kimodo(folder, spec, a.move, spec["check"])

    # 3. choose
    good = [(i, c) for i, c, g, m in cands if g and m]
    run["candidates"] = [{"id": i, "source": c.meta["source"], "gate_pass": g, "move_check_pass": m, "failed_gate": gate.failures(c.meta["gate"]),
                          "soft_failed": [k for k, r in c.meta["gate"]["soft"].items() if not r["ok"]], "move_check": c.meta["move_check"]} for i, c, g, m in cands]
    run["summary"] = {"candidates": len(cands), "pass_gate": sum(g for _, _, g, _ in cands), "pass_move_check": sum(m for _, _, _, m in cands), "pass_both": len(good)}
    best = min(good, key=lambda x: score(x[1])) if good else None
    run["best"] = None if best is None else best[0]
    if a.candidates:
        os.makedirs(a.candidates, exist_ok=True)
        for i, c, _, _ in cands:
            c.save(os.path.join(a.candidates, f"{a.move}_{i}.json"))
    if best:
        i, c = best
        c.save(os.path.join(out, "outputs", f"{a.move}.json"))
        sheet.contact_sheet(c, os.path.join(out, "outputs", f"{a.move}.png"), n=12, title=f"{a.move} ({i}) gate pass, move check pass")
        if a.ship:
            dest = os.path.join("public", "assets", "motion", f"{a.move}.json")
            c.save(dest)
            run["shipped_to"] = dest
    elif cands:  # a contact sheet of the nearest miss, so the failure can be looked at
        i, c, _, _ = min(cands, key=lambda x: abs(x[1].meta["move_check"].get("turn_in_window_deg", 0) - 360))
        sheet.contact_sheet(c, os.path.join(out, "outputs", f"{a.move}-nearest-miss.png"), n=12, title=f"{a.move} nearest miss: {i}")
    with open(os.path.join(out, "run.json"), "w") as f:
        json.dump(run, f, indent=2)
    print(json.dumps(run["summary"]), "best:", run["best"])
    sys.exit(0 if best else 2)


if __name__ == "__main__":
    main()
