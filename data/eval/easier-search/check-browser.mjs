import { chromium } from 'playwright';
import {mkdirSync} from 'node:fs';
const out='test-results/easier-search'; mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1280,height:800},reducedMotion:'reduce'});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>{localStorage.setItem('cc.world.v1',JSON.stringify({pieces:[{src:'box:8:0.5:2',x:0,z:0,y:0,yaw:0,scale:1},{src:'box:8:0.5:2',x:13,z:0,y:0,yaw:0,scale:1}],angle:0,offset:0,level:0,floor:'water'}));localStorage.setItem('cc.partner.pref','1');localStorage.setItem('cc.editor.glossary','hidden')});
await page.goto('http://localhost:5188/?mode=editor&easierview=1');
await page.waitForSelector('#easier',{timeout:60000,state:'attached'});
await page.waitForTimeout(4000);
console.log('baseline',await page.locator('html').evaluate(e=>({...e.dataset})));
await page.locator('#fixmenubtn').click(); await page.locator('#fixmenu-easier').click();
await page.waitForSelector('#canceleasier');
await page.screenshot({path:out+'/searching.png'});
await page.locator('#canceleasier').click();
if (!(await page.locator('#reply').innerText()).includes('cancelled')) throw Error('Cancel did not stop search');
console.log('cancelled',await page.locator('#reply').innerText());
await page.locator('#fixmenubtn').click(); await page.locator('#fixmenu-easier').click();
await page.waitForSelector('#canceleasier');
await page.locator('#angle').evaluate(el => el.dispatchEvent(new Event('input', { bubbles:true })));
if (!(await page.locator('#reply').innerText()).includes('layout changed')) throw Error('Editing did not cancel search');
console.log('edit cancellation passed');
await page.locator('#fixmenubtn').click(); await page.locator('#fixmenu-easier').click();
await page.waitForSelector('#applypreview',{timeout:90000});
await page.waitForFunction(()=>document.documentElement.dataset.preview==='clears',{timeout:90000});
console.log('winner',await page.locator('#reply').innerText());
if (await page.locator('html').getAttribute('data-preview-proof') !== 'cached') throw Error('Preview repeated winning search');
console.log('preview proof cached');
await page.screenshot({path:out+'/winner.png'});
await page.locator('#applypreview').click();
console.log('applied',await page.locator('#reply').innerText());
if (await page.locator('html').getAttribute('data-lane-proof') !== 'cached') throw Error('Apply repeated winning search');
console.log('lane proof cached');
await page.screenshot({path:out+'/applied.png'});
console.log('errors',errors); await browser.close();
if(errors.length)process.exit(1);
